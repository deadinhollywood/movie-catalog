// ============ Очистка и вставка ============
// Сначала удаляем все существующие фильмы, чтобы не было дублей при повторных запусках
db.prepare("DELETE FROM movies").run();

const insert = db.prepare(`
  INSERT INTO movies (title, year, genre, rating, duration, director, description, poster)
  VALUES (?, ?, ?, ?, ?, ?, ?, ?)
`);

// Транзакция: все вставки выполняются одной пачкой — быстро и атомарно
const insertMany = db.transaction((list) => {
  for (const m of list) {
    insert.run(
      m.title,
      m.year,
      m.genre,
      m.rating,
      m.duration,
      m.director,
      m.description,
      m.poster
    );
  }
});

insertMany(movies);

